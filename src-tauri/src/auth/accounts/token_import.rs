use anyhow::{bail, Result};
use sha2::{Digest, Sha256};

const TOKEN_PREFIX: &str = "sk-ant-oat01-";
const MAX_TOKEN_LENGTH: usize = 4096;

pub fn validate_token(token: &str) -> Result<&str> {
    let token = token.trim();
    let suffix = token.strip_prefix(TOKEN_PREFIX).unwrap_or_default();
    if token.len() > MAX_TOKEN_LENGTH
        || suffix.len() < 16
        || !suffix
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || c == b'-' || c == b'_')
    {
        bail!("Paste the OAuth token generated by claude setup-token, not an API key or command.");
    }
    Ok(token)
}

/// Local credential identifier, never an Anthropic account UUID.
pub fn token_id(token: &str) -> String {
    format!("token:{:x}", Sha256::digest(token.as_bytes()))
}

pub fn validate_label(label: Option<&str>) -> Result<Option<String>> {
    let label = label.map(str::trim).filter(|label| !label.is_empty());
    if label.is_some_and(|label| label.chars().count() > 80 || label.chars().any(char::is_control))
    {
        bail!("Use a label of at most 80 characters without line breaks.");
    }
    if label.is_some_and(|label| label.contains(TOKEN_PREFIX)) {
        bail!("Keep the token in the token field, not the account label.");
    }
    Ok(label.map(str::to_owned))
}
